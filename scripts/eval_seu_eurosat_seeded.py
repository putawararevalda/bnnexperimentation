"""
Deterministic (seeded) variant of `scripts/eval_seu_eurosat.py`.

=============================================================================
NOT THE DEFAULT. Do not use unless explicitly instructed.

All EuroSAT SEU results in the paper were produced by the UNSEEDED
`eval_seu_eurosat.py`. This script exists only as a precaution -- e.g. if a
reviewer asks for exact reproducibility, or if a specific result needs to be
regenerated byte-for-byte. Mixing output from this script with the unseeded
results would make run-to-run variance inconsistent across the grid.
=============================================================================

Difference from the default script
----------------------------------
`NewInjector._predict_probs` draws `num_samples` Monte-Carlo samples from the
Pyro guide. Those draws are unseeded in the default script, so the same config
re-run gives slightly different `initial_accuracy` / `accuracy_change` values.
That MC noise is inherent to the method, not a bug.

This variant pins the RNG immediately before every MC evaluation, so:
  * the baseline pass, and
  * each of the ~168 post-flip passes
draw an identical sample sequence. Re-running a config reproduces its CSV
exactly (same machine + same library versions).

Seeding strategy: `--seed` sets the base seed. Each flip additionally derives
a per-combo seed from (seed, timestamp, location_index, layer, module, bit,
param) so that flips stay independent of each other while remaining
reproducible AND resume-safe -- a config resumed halfway produces the same
values it would have in one uninterrupted run, which plain sequential seeding
cannot guarantee.

Usage (same CLI as the default script, plus --seed):
    uv run python scripts/eval_seu_eurosat_seeded.py --prior Gaussian_prior \\
        --search-dir results/eurosat/bayesian/results_eurosat_v02_01 \\
        --save-dir results/eurosat/seu_seeded/v02_01 --seed 42 --fast-smartpool

Always write to a SEPARATE --save-dir from the unseeded results.
"""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent.parent))

import argparse
import csv
import hashlib
import json
import os
import random

import numpy as np
import pyro
import torch

# Reuse the reference implementation wholesale; only RNG handling differs.
from scripts.eval_seu_eurosat import (
    CSV_FIELDS,
    TOTAL_COMBOS_PER_CONFIG,
    NewInjector,
    discover_configs,
    load_completed_combos,
    load_model,
    variant_from_search_dir,
)
from src.data.eurosat import load_data
from src.utils.notify import send_telegram_message


def set_global_seed(seed: int) -> None:
    """Seed every RNG the MC sampling path can touch."""
    random.seed(seed)
    np.random.seed(seed % (2 ** 32))
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)
    pyro.set_rng_seed(seed)


def combo_seed(base_seed: int, ts: str, location_index: int, layer: str,
               module: str, bit_i: int, param_name: str) -> int:
    """
    Derive a stable per-flip seed.

    Hashing the combo (rather than incrementing a counter) makes each flip's
    seed independent of evaluation ORDER. That matters for resume: a config
    that stops after 40 flips and resumes later still produces exactly the
    values it would have in one uninterrupted run.
    """
    key = f"{base_seed}|{ts}|{location_index}|{layer}|{module}|{bit_i}|{param_name}"
    digest = hashlib.sha256(key.encode()).digest()
    return int.from_bytes(digest[:4], "big")


class SeededInjector(NewInjector):
    """NewInjector with the MC sampling path pinned to a deterministic seed."""

    def __init__(self, *args, base_seed: int = 42, timestamp: str = "", **kwargs):
        self.base_seed = base_seed
        self.timestamp = timestamp
        # The baseline accuracy pass happens inside NewInjector.__init__, so
        # seed it before delegating.
        set_global_seed(combo_seed(base_seed, timestamp, 0, "__baseline__", "", 0, ""))
        super().__init__(*args, **kwargs)

    def run_seu(self, location_index, param_unique, parameter_name,
                layer, layer_module, bit_i, num_samples):
        set_global_seed(combo_seed(
            self.base_seed, self.timestamp, location_index,
            layer, layer_module, bit_i, parameter_name,
        ))
        return super().run_seu(location_index, param_unique, parameter_name,
                               layer, layer_module, bit_i, num_samples)


def parse_args():
    p = argparse.ArgumentParser(
        description="SEEDED/deterministic SEU evaluation for Bayesian EuroSAT "
                    "models. NOT the default pipeline -- see module docstring."
    )
    p.add_argument('--prior', type=str, default='Gaussian_prior',
                   choices=['Gaussian_prior', 'Laplace_prior', 'Uniform_prior'])
    p.add_argument('--save-dir', type=str, default='results/eurosat/seu_seeded',
                   help='Keep separate from the unseeded results directory.')
    p.add_argument('--search-dir', type=str, default='results/eurosat/bayesian')
    p.add_argument('--seed', type=int, default=42,
                   help='Base seed; per-flip seeds are derived from it.')
    p.add_argument('--limited-mode', dest='limited_mode', action='store_true')
    p.add_argument('--no-limited-mode', dest='limited_mode', action='store_false')
    p.add_argument('--fast-smartpool', action='store_true',
                   help='Use SmartPoolFast (bit-identical, ~8x faster end-to-end).')
    p.set_defaults(limited_mode=False)
    return p.parse_args()


def main():
    args = parse_args()
    os.makedirs(args.save_dir, exist_ok=True)
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    print("=" * 72)
    print("SEEDED SEU EVALUATION -- not the default pipeline.")
    print(f"base seed = {args.seed}")
    print("Do not mix this output with unseeded eval_seu_eurosat.py results.")
    print("=" * 72)

    set_global_seed(args.seed)
    _, test_loader = load_data(batch_size=54)

    variant = variant_from_search_dir(args.search_dir)
    smartpool_switch = variant == "smartpool"
    dropout_switch = variant == "dropout"
    print(f"Search-dir variant: {variant} "
          f"(smartpool={smartpool_switch}, dropout={dropout_switch})")

    prior_map = {'Gaussian_prior': 'gaussian', 'Laplace_prior': 'laplace',
                 'Uniform_prior': 'uniform'}
    target_prior = prior_map[args.prior]

    entries = discover_configs(args.search_dir, args.save_dir)
    print(f"Configs found: {len(entries)}")

    entries = [e for e in entries if e['config']['prior'] == target_prior]
    print(f"After prior filter ({args.prior}): {len(entries)}")

    if args.limited_mode:
        entries = [e for e in entries if e['config']['prior_params']['b'] == 1.0]
        print(f"After limited mode (b=1.0) filter: {len(entries)}")

    # Only skip a config entirely if its own CSV already has all 168 rows.
    entries = [
        e for e in entries
        if len(load_completed_combos(e['csv_path'])) < TOTAL_COMBOS_PER_CONFIG
    ]
    print(f"After excluding completed: {len(entries)}")

    config_files = {e['stem']: e['config_file'] for e in entries}
    model_files = {e['stem']: e['model_file'] for e in entries}
    param_files = {e['stem']: e['param_file'] for e in entries}

    guide_map = {'gaussian': 'AutoNormal', 'laplace': 'AutoLaplace', 'uniform': 'AutoUniform'}
    param_map = {'gaussian': ['locs', 'scales'], 'laplace': ['locs', 'scales'],
                 'uniform': ['lows', 'widths']}
    bit_list = [0, 1, 3, 6, 10, 15, 21]

    for exp_idx, entry in enumerate(entries, start=1):
        stem, ts = entry['stem'], entry['ts']
        pyro.clear_param_store()
        send_telegram_message(
            title=f"EuroSAT SEU (seeded) {exp_idx}/{len(entries)}",
            message=f"config={stem}, prior={args.prior}, seed={args.seed}"
        )

        model, param_store_path, model_config = load_model(
            stem, args.search_dir, config_files, model_files, param_files, device,
            smartpool_switch=smartpool_switch, dropout_switch=dropout_switch,
            fast_smartpool=args.fast_smartpool,
        )
        prior = model_config['prior']
        param_unique = guide_map[prior]
        parameter_names = param_map[prior]

        newinj = SeededInjector(
            trained_model=model, device=device,
            test_loader=test_loader, num_samples=10,
            pyro_param_store_path=param_store_path,
            base_seed=args.seed, timestamp=stem,
        )

        csv_path = entry['csv_path']
        done_combos = load_completed_combos(csv_path)
        if done_combos:
            print(f"Resuming {stem}: {len(done_combos)}/{TOTAL_COMBOS_PER_CONFIG} combos done")

        file_exists = os.path.exists(csv_path)
        with open(csv_path, "a", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=CSV_FIELDS)
            if not file_exists:
                writer.writeheader()
                f.flush()

            for attack_loc in ["beginning", "end"]:
                target_idx = 0 if attack_loc == "beginning" else -1
                for layer in ["conv1", "conv2", "fc1"]:
                    for module in ["weight", "bias"]:
                        for bit_i in bit_list:
                            for param_name in parameter_names:
                                combo_key = (target_idx, layer, module, bit_i, param_name)
                                if combo_key in done_combos:
                                    continue
                                print(f"SEU: {layer}.{module} bit={bit_i} param={param_name}")
                                result = newinj.run_seu(
                                    target_idx, param_unique, param_name,
                                    layer, module, bit_i, num_samples=10
                                )
                                writer.writerow({
                                    "activation_fn": model_config['activation'],
                                    "prior": prior,
                                    "variant": variant,
                                    "best_accuracy": model_config.get('best_accuracy', None),
                                    "prior_mu": model_config['prior_params']['mu'],
                                    "prior_b": model_config['prior_params']['b'],
                                    "param_type": param_name,
                                    "location_index": target_idx,
                                    "location_layer": layer,
                                    "location_module": module,
                                    "bit_index": bit_i,
                                    "initial_accuracy": newinj.initial_accuracy,
                                    "accuracy_after_seu": newinj.initial_accuracy + result["accuracy_change"],
                                    "accuracy_change": result["accuracy_change"],
                                    "softmax_difference": result["softmax_difference"],
                                    "mean_abs_difference": result["absolute_difference"],
                                    "original_bit_condition": result.get("original_bit_condition"),
                                    "remarks": result.get("remarks", ""),
                                })
                                f.flush()

        print(f"Results saved for {stem} -> {os.path.basename(csv_path)}")
        send_telegram_message(
            title=f"EuroSAT SEU (seeded) Done {exp_idx}/{len(entries)}",
            message=f"config={stem}, prior={prior}, seed={args.seed}"
        )


if __name__ == "__main__":
    main()
